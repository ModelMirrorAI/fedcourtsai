"""The command prefixes a predict or evaluate cell may not run, in each engine's own form.

A cell's tooling is fixed before its engine starts: the project venv, the
pinned engine CLI, and ``fedcourts`` on the shell's ``PATH`` (``fedcourts
pdf-text`` reads a PDF). A package installed mid-turn is code no review saw,
fetched from an index on the cell's open network and run beside the cell's
outputs, so a run-time install is refused rather than left to the prompt.

One list, rendered three ways, because each engine enforces a refusal in its
own configuration surface:

- **claude-code** — ``permissions.deny`` rules in the settings the cell step
  hands the CLI (:func:`claude_deny_rules`). Deny rules hold under
  ``bypassPermissions``, the mode the cells run in.
- **codex** — an execpolicy rules file of ``forbidden`` prefix rules
  (:func:`codex_rules`), placed under the codex account's ``CODEX_HOME``.
- **gemini** — a policy file of ``deny`` rules on ``run_shell_command``
  (:func:`gemini_policy_toml`), named in the settings' ``policyPaths``. Its
  tier outranks the ``--yolo`` allow-all rule.

What each refuses is a **command prefix**, not an outcome. A command the
engine parses into one of these prefixes is refused — gemini and codex split
``&&`` / ``;`` chains, and gemini reads into ``bash -c`` — but a script file
the agent writes and then runs, or an installer invoked under a name not
listed here, is not seen. The refusal closes the ordinary install path; it is
not a sandbox, and docs/security.md says so.
"""

from __future__ import annotations

import json
from typing import Final

#: Each refused command, as the argv tokens it starts with.
INSTALL_COMMAND_PREFIXES: Final[tuple[tuple[str, ...], ...]] = (
    ("pip", "install"),
    ("pip3", "install"),
    ("python", "-m", "pip"),
    ("python3", "-m", "pip"),
    ("uv", "pip"),
    ("uv", "add"),
    ("uv", "tool"),
    ("uvx",),
    ("pipx",),
    ("conda",),
    ("mamba",),
    ("npm", "install"),
    ("npm", "i"),
    ("npm", "ci"),
    ("npm", "add"),
    ("npx",),
    ("pnpm",),
    ("yarn",),
    ("apt-get",),
    ("apt",),
    ("sudo",),
    ("gem", "install"),
    ("cargo", "install"),
    ("go", "install"),
)

#: Why a refused command was refused, as the engines that carry a reason show it.
JUSTIFICATION: Final = (
    "a fedcourtsai cell installs nothing at run time; read a PDF with `fedcourts pdf-text`"
)

#: The file names the cell workflows write the codex and gemini renderings to.
CODEX_RULES_FILENAME: Final = "fedcourts-cell.rules"
GEMINI_POLICY_FILENAME: Final = "fedcourts-cell.toml"


def claude_deny_rules() -> list[str]:
    """The ``permissions.deny`` entries, one ``Bash(<prefix> *)`` rule per prefix."""
    return [f"Bash({' '.join(prefix)} *)" for prefix in INSTALL_COMMAND_PREFIXES]


def codex_rules() -> str:
    """The execpolicy rules file: one ``forbidden`` prefix rule per prefix."""
    lines = ["# Generated by `fedcourts cell-policy --engine codex`; do not edit."]
    lines += [
        f'prefix_rule(pattern={json.dumps(list(prefix))}, decision="forbidden", '
        + f"justification={json.dumps(JUSTIFICATION)})"
        for prefix in INSTALL_COMMAND_PREFIXES
    ]
    return "\n".join(lines) + "\n"


#: The rule's priority inside its tier. The file is loaded at the user tier,
#: which every rule of the CLI's own default tier — the ``--yolo`` allow-all
#: among them — sits below whatever the number.
GEMINI_RULE_PRIORITY: Final = 900


def gemini_policy_toml() -> str:
    """The policy file: one ``deny`` rule on the shell tool over every prefix."""
    prefixes = json.dumps([" ".join(prefix) for prefix in INSTALL_COMMAND_PREFIXES])
    return (
        "# Generated by `fedcourts cell-policy --engine gemini`; do not edit.\n"
        "[[rule]]\n"
        'toolName = "run_shell_command"\n'
        f"commandPrefix = {prefixes}\n"
        'decision = "deny"\n'
        f"priority = {GEMINI_RULE_PRIORITY}\n"
        f"denyMessage = {json.dumps(JUSTIFICATION)}\n"
    )


def render(engine: str) -> str:
    """The engine's rendering, as the file or JSON the cell workflow writes."""
    if engine == "claude-code":
        return json.dumps(claude_deny_rules(), indent=2) + "\n"
    if engine == "codex":
        return codex_rules()
    if engine == "gemini":
        return gemini_policy_toml()
    raise ValueError(f"no cell policy for engine {engine!r}")
